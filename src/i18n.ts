const PAGE_TITLE = "Chińczyk";
const PAGE_DESCRIPTION = "Klasyczna gra dla 2–4 graczy przy jednym ekranie.";
export type Language = "pl" | "en";
const storageKey = "chinczyk-language";
export function detectLanguage(saved: string | null, languages: readonly string[]): Language {
  if (saved === "pl" || saved === "en") return saved;
  for (const language of languages) {
    const code = language.toLowerCase().split(/[-_]/)[0];
    if (code === "pl" || code === "en") return code;
  }
  return "en";
}
function initialLanguage(): Language {
  let saved: string | null = null;
  try { saved = localStorage.getItem(storageKey); } catch { /* Storage may be blocked. */ }
  return detectLanguage(saved, typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]);
}
export let language = initialLanguage();
const listeners = new Set<() => void>();
export function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}
export function setLanguage(value: Language) {
  language = value;
  try { localStorage.setItem(storageKey, value); } catch { /* Switching still works without persistence. */ }
  updateDocument();
  listeners.forEach(listener => listener());
}
export function t(source: string, values: Record<string, string | number> = {}): string {
  const key = source.replace(/\s+/g, " ").trim();
  const translated = language === "en" ? translations[key] ?? source : source;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
function updateDocument() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = language;
  document.title = t(PAGE_TITLE);
  document.querySelector('meta[name="description"]')?.setAttribute("content", t(PAGE_DESCRIPTION));
}
updateDocument();
